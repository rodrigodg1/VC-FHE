#!/usr/bin/env node
/**
 * Generate a kms-core-client TOML configuration for an n-party Zama KMS
 * threshold deployment (zama-ai/kms), matching the schema of the upstream
 * `core-client/config/client_local_threshold.toml` (n=4, t=1 defaults:
 * num_majority=2, num_reconstruct=3, ports 50100/50200/50300/50400,
 * s3 http://localhost:9000/kms, object_folder PUB-p{i}).
 *
 * Robustness rule (Noah's Ark MPC, robust threshold): n >= 3t + 1.
 * Derived response counts follow the upstream n=4/t=1 values:
 *   num_majority    = t + 1
 *   num_reconstruct = 2t + 1
 * (For n=4, t=1 this reproduces exactly the upstream 2 and 3.)
 *
 * Local multi-instance (single machine, default ports):
 *   node scripts/generate-client-config.mjs --n 4 > client_threshold_4.toml
 *   node scripts/generate-client-config.mjs --n 7 --threshold 2 > client_threshold_7.toml
 *
 * Multi-machine (one KMS core per computer):
 *   node scripts/generate-client-config.mjs \
 *     --cores 10.0.0.11:50100,10.0.0.12:50100,10.0.0.13:50100,10.0.0.14:50100 \
 *     --s3 http://10.0.0.11:9000/kms > client_threshold_lan.toml
 */
export function deriveThreshold(n) {
  // Largest t with n >= 3t + 1 (robust MPC).
  return Math.floor((n - 1) / 3);
}

export function buildConfig(options = {}) {
  const cores = [];
  if (options.cores) {
    const list = Array.isArray(options.cores)
      ? options.cores
      : String(options.cores).split(",").map((s) => s.trim()).filter(Boolean);
    for (const entry of list) {
      if (!/^[^:]+:\d+$/.test(entry)) {
        throw new Error(`--cores entries must be host:port, received: ${entry}`);
      }
      cores.push(entry);
    }
  } else {
    const n = Number.parseInt(options.n ?? 4, 10);
    if (!Number.isInteger(n) || n < 4) {
      throw new Error("--n must be an integer >= 4 (robust threshold needs n >= 3t+1, t >= 1)");
    }
    const basePort = Number.parseInt(options.basePort ?? 50100, 10);
    const host = options.host ?? "localhost";
    for (let i = 0; i < n; i += 1) {
      // Upstream local pattern: 50100, 50200, 50300, 50400, ...
      cores.push(`${host}:${basePort + i * 100}`);
    }
  }

  const n = cores.length;
  const t =
    options.threshold !== undefined
      ? Number.parseInt(options.threshold, 10)
      : deriveThreshold(n);
  if (!Number.isInteger(t) || t < 1) {
    throw new Error("threshold t must be an integer >= 1");
  }
  if (n < 3 * t + 1) {
    throw new Error(`robust threshold requires n >= 3t+1; got n=${n}, t=${t}`);
  }

  const numMajority = t + 1;
  const numReconstruct = 2 * t + 1;
  const fheParams = options.fheParams ?? "Default";
  if (!["Test", "Default"].includes(fheParams)) {
    throw new Error('--fhe-params must be "Test" or "Default"');
  }
  const decryptionMode = options.decryptionMode ?? "NoiseFloodSmall";
  const s3 = options.s3 ?? "http://localhost:9000/kms";

  const lines = [
    `# kms-core-client config generated by VC-FHE/threshold-kms (schema: zama-ai/kms core-client/config/client_local_threshold.toml)`,
    `# n=${n} cores, threshold t=${t} (robust MPC: n >= 3t+1)`,
    `kms_type = "threshold"`,
    `num_parties = ${n}`,
    `num_majority = ${numMajority}`,
    `num_reconstruct = ${numReconstruct}`,
    `# Must match the deployed core/service setting.`,
    `decryption_mode = "${decryptionMode}"`,
    fheParams === "Test"
      ? `fhe_params = "Test" # small, insecure parameters for testing; use "Default" for secure parameters`
      : `fhe_params = "Default" # large, secure parameters`,
    ``
  ];
  cores.forEach((address, index) => {
    const pid = index + 1;
    lines.push(
      `[[cores]]`,
      `party_id = ${pid}`,
      `address = "${address}"`,
      `s3_endpoint = "${s3}"`,
      `object_folder = "PUB-p${pid}"`,
      ``
    );
  });
  lines.push(
    `# Default EIP-712 domain (matches the upstream built-in default).`,
    `[default_domain]`,
    `name = "Authorization token"`,
    `version = "1"`,
    `chain_id = 8006`,
    `verifying_contract = "0x66f9664f97F2b50F62D13eA064982f936dE76657"`
  );

  return {
    toml: `${lines.join("\n")}\n`,
    summary: { n, t, numMajority, numReconstruct, fheParams, decryptionMode, cores, s3 }
  };
}

function parseArgs(argv) {
  const options = {};
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    const next = () => argv[++i];
    if (a === "--n") options.n = next();
    else if (a === "--threshold" || a === "-t") options.threshold = next();
    else if (a === "--cores") options.cores = next();
    else if (a === "--host") options.host = next();
    else if (a === "--base-port") options.basePort = next();
    else if (a === "--s3") options.s3 = next();
    else if (a === "--fhe-params") options.fheParams = next();
    else if (a === "--decryption-mode") options.decryptionMode = next();
    else throw new Error(`Unknown argument: ${a}`);
  }
  return options;
}

const invokedDirectly =
  process.argv[1] && import.meta.url.endsWith(process.argv[1].split(/[\\/]/).pop());
if (invokedDirectly) {
  const { toml, summary } = buildConfig(parseArgs(process.argv.slice(2)));
  process.stdout.write(toml);
  process.stderr.write(`# ${JSON.stringify(summary)}\n`);
}
